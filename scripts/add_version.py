#!/usr/bin/env python3
"""Pin a Valkey release in versions.bzl, make sure its series has a patch, and
regenerate valkey_test_builds so CI smoke tests it."""

import argparse
import hashlib
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
VERSIONS_BZL = REPO_ROOT / "valkey_bazel" / "versions.bzl"
PATCHES_DIR = REPO_ROOT / "valkey_bazel" / "patches"
TEST_BUILDS = REPO_ROOT / "valkey_test_builds"

ENTRY_RE = re.compile(r'^    "(\d+\.\d+\.\d+)": _valkey\("\d+\.\d+\.\d+", "([0-9a-f]{64})"\),\n', re.M)

MODULE_HEADER = """\
module(name = "valkey_test_builds")

# Must come before anything that pulls in rules_cc, so its Xcode toolchain is registered ahead of rules_cc's
# autodetected one. That one picks up whatever ld64.lld is on PATH, and nix's LLD segfaults linking Mach-O.
bazel_dep(name = "apple_support", version = "1.23.1")
bazel_dep(name = "valkey_bazel")
local_path_override(
    module_name = "valkey_bazel",
    path = "../valkey_bazel",
)

bazel_dep(name = "sysroots")
local_path_override(
    module_name = "sysroots",
    path = "../sysroots",
)

sysroots = use_extension("@sysroots//:extension.bzl", "sysroots")
sysroots.sysroot(
    module_name = "sysroot_linux_arm64",
    tarball = "@sysroots//:sysroot-linux-arm64.tar",
)
sysroots.sysroot(
    module_name = "sysroot_linux_amd64",
    tarball = "@sysroots//:sysroot-linux-amd64.tar",
)
use_repo(sysroots, "sysroot_linux_amd64", "sysroot_linux_arm64")

bazel_dep(name = "tar.bzl", version = "0.10.9")
bazel_dep(name = "toolchains_llvm", version = "1.9.1")

llvm = use_extension("@toolchains_llvm//toolchain/extensions:llvm.bzl", "llvm")

_LLVM_TOOLCHAINS = [
    {
        "name": "llvm_toolchain",
        "exec_os": "",
        "exec_arch": "",
    },
    {
        "name": "llvm_toolchain_exec_aarch64",
        "exec_os": "linux",
        "exec_arch": "aarch64",
    },
    {
        "name": "llvm_toolchain_exec_x86_64",
        "exec_os": "linux",
        "exec_arch": "x86_64",
    },
]

_LLVM_SYSROOTS = [
    {
        "target": "linux-aarch64",
        "label": "@sysroot_linux_arm64//:files",
    },
    {
        "target": "linux-x86_64",
        "label": "@sysroot_linux_amd64//:files",
    },
]

_LLVM_VERSIONS = {
    "linux-x86_64": "20.1.2",
    "linux-aarch64": "20.1.2",
}

_LLVM_SHA256 = {
    "linux-x86_64": "96506dbe7b7acfa8ee719c668e2af73623018e9312bf60062bffca8f5a7f6c5f",
    "linux-aarch64": "c80099d630e9e0dee846202d35a5b965ffec7694eb1bf39d965db88dbab30178",
}

_LLVM_STDLIB = {
    "linux-x86_64": "stdc++",
    "linux-aarch64": "stdc++",
}

_llvm_sysroots = [
    llvm.sysroot(
        name = toolchain["name"],
        label = sysroot["label"],
        targets = [sysroot["target"]],
    )
    for toolchain in _LLVM_TOOLCHAINS
    for sysroot in _LLVM_SYSROOTS
]

_llvm_toolchains = [
    llvm.toolchain(
        name = toolchain["name"],
        exec_arch = toolchain["exec_arch"],
        exec_os = toolchain["exec_os"],
        llvm_versions = _LLVM_VERSIONS,
        sha256 = _LLVM_SHA256,
        stdlib = _LLVM_STDLIB,
    )
    for toolchain in _LLVM_TOOLCHAINS
]

use_repo(llvm, "llvm_toolchain", "llvm_toolchain_exec_aarch64", "llvm_toolchain_exec_x86_64")

register_toolchains("@llvm_toolchain//:all")

register_toolchains("@llvm_toolchain_exec_aarch64//:all")

register_toolchains("@llvm_toolchain_exec_x86_64//:all")

valkey = use_extension("@valkey_bazel//:extension.bzl", "valkey")
"""

BUILD_HEADER = """\
load("@valkey_bazel//:defs.bzl", "valkey_smoke_test")

# Generated by scripts/add_version.py from valkey_bazel/versions.bzl.
"""


def version_key(version):
    return tuple(int(p) for p in version.split("."))


def repo_name(version):
    return "valkey_" + version.replace(".", "_")


def read_versions():
    return {m[1]: m[2] for m in ENTRY_RE.finditer(VERSIONS_BZL.read_text())}


def tarball_url(version):
    return f"https://github.com/valkey-io/valkey/archive/refs/tags/{version}.tar.gz"


def update_versions_bzl(version, sha256):
    src = VERSIONS_BZL.read_text()
    matches = list(ENTRY_RE.finditer(src))
    if not matches:
        sys.exit(f"error: couldn't find the VERSIONS entries in {VERSIONS_BZL}")

    existing = next((m for m in matches if m[1] == version), None)
    if existing and existing[2] == sha256:
        print(f"versions.bzl already pins {version}", file=sys.stderr)
        return
    if existing:
        print(f"versions.bzl: updating sha256 for {version} (was {existing[2]})", file=sys.stderr)
        start, end = existing.span(2)
        src = src[:start] + sha256 + src[end:]
    else:
        print(f"versions.bzl: adding {version}", file=sys.stderr)
        line = f'    "{version}": _valkey("{version}", "{sha256}"),\n'
        later = next((m for m in matches if version_key(m[1]) > version_key(version)), None)
        pos = later.start() if later else matches[-1].end()
        src = src[:pos] + line + src[pos:]
    VERSIONS_BZL.write_text(src)


def write_test_builds(versions):
    ordered = sorted(versions, key=version_key)
    module = MODULE_HEADER + "".join(f'valkey.add_version(version = "{v}")\n' for v in ordered)
    module += "use_repo(\n    valkey,\n" + "".join(f'    "{repo_name(v)}",\n' for v in sorted(ordered, key=repo_name)) + ")\n"
    (TEST_BUILDS / "MODULE.bazel").write_text(module)

    build = BUILD_HEADER + "".join(
        "\nvalkey_smoke_test(\n"
        f'    name = "{repo_name(v)}_smoke_test",\n'
        f'    repo = "@{repo_name(v)}",\n'
        f'    version = "{v}",\n'
        ")\n"
        for v in ordered
    )
    (TEST_BUILDS / "BUILD.bazel").write_text(build)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version", nargs="?", help="release to add, e.g. 9.1.3. Omit to only regenerate valkey_test_builds.")
    parser.add_argument("--sha256", help="sha256 of the source tarball; downloaded and hashed if omitted")
    args = parser.parse_args()

    if args.version:
        m = re.fullmatch(r"(\d+)\.(\d+)\.\d+", args.version)
        if not m:
            sys.exit("error: version must look like 9.1.3")

        tarball = None
        sha256 = args.sha256
        if not sha256:
            with urllib.request.urlopen(tarball_url(args.version)) as resp:
                tarball = resp.read()
            sha256 = hashlib.sha256(tarball).hexdigest()
        update_versions_bzl(args.version, sha256)

        if not (PATCHES_DIR / f"{m[1]}.{m[2]}.patch").exists():
            print(f"no patch for the {m[1]}.{m[2]} series yet, generating one", file=sys.stderr)
            subprocess.run([sys.executable, REPO_ROOT / "scripts" / "make_patch.py", args.version], check=True)

    write_test_builds(read_versions())
    if args.version:
        print(f"Added {args.version}. Run scripts/test.sh, or:", file=sys.stderr)
        print(f"  (cd valkey_test_builds && bazel test //:{repo_name(args.version)}_smoke_test)", file=sys.stderr)


if __name__ == "__main__":
    main()
